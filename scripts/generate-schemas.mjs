import { createGenerator } from "ts-json-schema-generator";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { format, resolveConfig } from "prettier";
import { deepStrictEqual } from "node:assert";

const check = process.argv.includes("--check");
function output(path, content) {
    if (check) {
        if (readFileSync(path, "utf8") !== content)
            throw new Error(
                "Generated schema differs: " + path + ". Run npm run schemas.",
            );
    } else writeFileSync(path, content);
}

function modernize(value) {
    if (Array.isArray(value)) return value.map(modernize);
    if (!value || typeof value !== "object") return value;
    const result = {};
    for (const [key, child] of Object.entries(value)) {
        if (key === "$schema") continue;
        if (key === "definitions") result.$defs = modernize(child);
        else if (key === "$ref")
            result.$ref = child.replace("#/definitions/", "#/$defs/");
        else if (key === "items" && Array.isArray(child)) {
            result.prefixItems = modernize(child);
            result.items = false;
        } else if (key === "additionalProperties" && child === false) {
            result.additionalProperties = true; // Forward-compatible additive fields.
        } else result[key] = modernize(child);
    }
    return result;
}

const schemas = {};
for (const [type, name] of Object.entries({
    ChartPayload: "chart-payload",
    ChartResult: "chart-result",
    AdapterManifest: "adapter-manifest",
    DatasetPayload: "dataset",
})) {
    const raw = createGenerator({
        path: "packages/sdk/src/types.ts",
        tsconfig: "tsconfig.json",
        type,
        skipTypeCheck: true,
        expose: "all",
    }).createSchema(type);
    const schema = {
        $schema: "https://json-schema.org/draft/2020-12/schema",
        ...modernize(raw),
    };
    schemas[name] = schema;
    for (const directory of ["packages/sdk/schemas", "resources/schemas"]) {
        mkdirSync(directory, { recursive: true });
        output(
            directory + "/" + name + ".v1.json",
            JSON.stringify(schema, null, 2) + "\n",
        );
    }
}
output(
    "packages/sdk/src/schemas.ts",
    await format(
        "// Generated by npm run schemas.\nexport const schemas: Record<string, object> = " +
            JSON.stringify(schemas) +
            ";\n",
        {
            ...(await resolveConfig("packages/sdk/src/schemas.ts", {
                editorconfig: true,
            })),
            filepath: "packages/sdk/src/schemas.ts",
        },
    ),
);
for (const adapter of ["echarts", "shadcn"])
    deepStrictEqual(
        JSON.parse(readFileSync(`resources/manifests/${adapter}.json`, "utf8")),
        JSON.parse(
            readFileSync(
                `resources/react/adapters/${adapter}/manifest.json`,
                "utf8",
            ),
        ),
        `PHP and JavaScript ${adapter} manifests differ.`,
    );
console.log(
    check
        ? "Generated schemas and adapter manifests match."
        : "Generated schemas updated; adapter manifests match.",
);
