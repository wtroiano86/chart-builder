# Chart Builder

This application uses wtroiano/chart-builder. Read vendor/wtroiano/chart-builder/docs/consumers/getting-started.md and the guide for the task before changing chart definitions.

Use result(request()) for Inertia chart props. Authorize before loading data, scope provider queries to the tenant, use explicit cache variation and keep chart names stable. Prepared data and SQL aggregation share a typed, versioned payload. Never place executable JavaScript in PHP options.

Published React sources live under resources/js/vendor/chart-builder. Import the full entry for ECharts or core for another adapter. Match PHP and JavaScript manifests and SDK versions. Preserve shared filter coordination, accessible data and denial clearing.

Use the chart-builder-development, chart-builder-react and chart-builder-adapters skills for the relevant work. Consumer docs, runtime signatures and schemas are the source of concrete API behavior.
