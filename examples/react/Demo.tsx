import { useMemo, useState } from "react";
import { Link } from "@inertiajs/react";
import { Chart, type ChartResult } from "../../resources/react";
import "./demo.css";

interface DemoProps {
    revenueChart: ChartResult;
    regionalChart: ChartResult;
    productChart: ChartResult;
    targetChart: ChartResult;
    scatterChart: ChartResult;
    hierarchyChart: ChartResult;
    summary: { orders: number; revenue: number; charts: number };
    phpSource: string;
}

export function Demo(props: DemoProps) {
    const [theme, setTheme] = useState<"light" | "dark">("light");
    const charts = useMemo(
        () =>
            (
                [
                    ["revenue", "revenueChart", props.revenueChart],
                    ["regions", "regionalChart", props.regionalChart],
                    ["products", "productChart", props.productChart],
                    ["targets", "targetChart", props.targetChart],
                    ["engagement", "scatterChart", props.scatterChart],
                    ["portfolio", "hierarchyChart", props.hierarchyChart],
                ] satisfies Array<[string, string, ChartResult]>
            ).map(([name, propName, result]) => {
                return {
                    name,
                    propName,
                    result:
                        result.status === "ready"
                            ? {
                                  ...result,
                                  chart: {
                                      ...result.chart,
                                      appearance: {
                                          ...result.chart.appearance,
                                          theme,
                                      },
                                  },
                              }
                            : result,
                };
            }),
        [
            props.revenueChart,
            props.regionalChart,
            props.productChart,
            props.targetChart,
            props.scatterChart,
            props.hierarchyChart,
            theme,
        ],
    );

    return (
        <main className="demo-shell" data-theme={theme}>
            <div className="demo-content">
                <header className="demo-header">
                    <a className="demo-brand" href="/demo">
                        <span className="demo-mark" aria-hidden="true">
                            ▥
                        </span>{" "}
                        Chart Builder{" "}
                        <span className="demo-badge">LOCAL PREVIEW</span>
                    </a>
                    <nav aria-label="Preview navigation">
                        <Link href="/gallery">
                            36 chart examples <span aria-hidden="true">↗</span>
                        </Link>
                        <label className="demo-theme">
                            Theme{" "}
                            <select
                                value={theme}
                                onChange={(event) =>
                                    setTheme(
                                        event.target.value as "light" | "dark",
                                    )
                                }
                            >
                                <option value="light">Light</option>
                                <option value="dark">Dark</option>
                            </select>
                        </label>
                    </nav>
                </header>
                <div className="demo-intro">
                    <p className="demo-eyebrow">
                        LARAVEL · INERTIA · REACT · ECHARTS
                    </p>
                    <h1>Live PHP chart preview</h1>
                    <p>
                        Change filters, inspect the data, and download the
                        results. Every chart below is generated by the package
                        from PHP.
                    </p>
                </div>
                <div
                    className="demo-metrics"
                    aria-label="Sample dataset summary"
                >
                    <div>
                        <span>Sample revenue · full dataset</span>
                        <strong>
                            {new Intl.NumberFormat("en-US", {
                                style: "currency",
                                currency: "USD",
                                maximumFractionDigits: 0,
                            }).format(props.summary.revenue)}
                        </strong>
                    </div>
                    <div>
                        <span>Sample orders</span>
                        <strong>{props.summary.orders.toLocaleString()}</strong>
                    </div>
                    <div>
                        <span>PHP-generated charts</span>
                        <strong>
                            {props.summary.charts.toString().padStart(2, "0")}
                        </strong>
                    </div>
                    <div>
                        <span>Reporting period</span>
                        <strong>
                            2026 <small>sample year</small>
                        </strong>
                    </div>
                </div>
                <div className="demo-grid">
                    {charts.map((chart, index) => (
                        <div
                            className={
                                index === 0 || index === 5
                                    ? "demo-wide"
                                    : undefined
                            }
                            key={chart.name}
                        >
                            <Chart
                                name={chart.name}
                                propName={chart.propName}
                                result={chart.result}
                            />
                        </div>
                    ))}
                </div>
                <details className="demo-source">
                    <summary>View the PHP chart definitions</summary>
                    <p>
                        Edit <code>examples/charts.php</code> to try your own
                        definitions. This preview reloads when the PHP examples
                        change.
                    </p>
                    <pre>
                        <code>{props.phpSource}</code>
                    </pre>
                </details>
                <footer className="demo-footer">
                    <span>
                        Deterministic sample data · isolated SQLite database
                    </span>
                    <Link href="/charts">Transport test page</Link>
                </footer>
            </div>
        </main>
    );
}
